"""Reuse settled screening groups and replay their immutable rollout snapshots."""

import asyncio
import hashlib
import json
import logging
import tomllib
from pathlib import Path

from miles.utils.recording.outbox import DurableRolloutOutbox

logger = logging.getLogger(__name__)


def group_trials(group):
    """Older exports used round zero; resumed attempts retain their actual IDs."""
    trials = group.get("trial_ids", list(range(len(group["rewards"]))))
    if (
        len(trials) != len(group["rewards"])
        or len(set(trials)) != len(trials)
        or any(type(trial) is not int or trial < 0 for trial in trials)
    ):
        raise ValueError("Invalid recording trial IDs in screening group")
    return trials


def recording_details(samples):
    if not any(sample.recording_source is not None for sample in samples):
        return {}
    sources = {sample.recording_source for sample in samples}
    if None in sources or len(sources) != 1 or any(sample.recording_trial_id is None for sample in samples):
        raise ValueError("Screening group has inconsistent recording provenance")
    return {
        "trial_ids": [sample.recording_trial_id for sample in samples],
        "recording_source": samples[0].recording_source,
    }


def completed_groups(directory, *, source_sha256, total, n_samples, early_stop):
    directory = Path(directory).resolve()
    summary = json.loads((directory / "summary.json").read_text())
    if (summary["source_sha256"], summary["total"], summary["samples_per_prompt"]) != (
        source_sha256, total, n_samples
    ):
        raise ValueError("Resume source dataset or sample count differs from this sweep")
    if bool(summary.get("early_stop", False)) != early_stop:
        raise ValueError("Resume source uses a different early-stop policy")
    result, seen = [], set()
    # The append log, not the periodically flushed summary counts, is authoritative.
    for line in (directory / "groups.jsonl").read_text().splitlines():
        group = json.loads(line)
        index = group["source_index"]
        if type(index) is not int or not 0 <= index < total or index in seen:
            raise ValueError(f"Invalid or duplicate resume source index: {index}")
        seen.add(index)
        if group["decision"] == "failed":
            continue
        rewards = group["rewards"]
        mixed = bool(rewards) and 0 in rewards and 1 in rewards
        valid_length = len(rewards) == n_samples or (early_stop and mixed and 2 <= len(rewards) < n_samples)
        if not rewards or not valid_length or any(r not in (0, 1) for r in rewards):
            raise ValueError(f"Incomplete confirmed resume group: {index}")
        decision = "kept" if mixed else "all_one" if rewards[0] == 1 else "all_zero"
        if group["decision"] != decision:
            raise ValueError(f"Resume decision disagrees with rewards: {index}")
        group_trials(group)
        # Keep the original snapshot location across repeated resumes, including
        # an interruption before the intermediate run finishes replaying to DB.
        result.append({
            **group,
            "recording_source": group.get("recording_source", str(directory.parent / "rollout_records")),
        })
    return result


def validate_recording_sources(groups, *, collection, policy_checkpoint=None):
    """Check identities and snapshot availability before any new GPU requests."""
    sources = {}
    for group in groups:
        source = Path(group["recording_source"])
        if source not in sources:
            manifest = json.loads((source / "run.json").read_text())
            if manifest["collection"] != collection:
                raise ValueError("Inherited rollout collection differs from the current input")
            if policy_checkpoint is not None:
                config = tomllib.loads((source.parent / "config.toml").read_text())
                if config["train"]["hf_checkpoint"] != policy_checkpoint:
                    raise ValueError("Inherited rollouts were generated by a different policy checkpoint")
            names = {p.name for subdir in ("committed", "pending") for p in (source / subdir).glob("*.json.gz")}
            sources[source] = (manifest, names)
        _, names = sources[source]
        for trial in group_trials(group):
            name = hashlib.sha256(f"{group['source_index']}:{trial}".encode()).hexdigest() + ".json.gz"
            if name not in names:
                raise FileNotFoundError(f"Missing confirmed rollout snapshot: {source / name}")
    return {source: manifest for source, (manifest, _) in sources.items()}


def validate_reused_recording(groups, directory, identity):
    """Require every settled trial in the original spool; never rewrite its provenance."""
    directory = Path(directory)
    manifest = json.loads((directory / "run.json").read_text())
    if any(manifest[key] != identity[key] for key in ("model", "run", "collection")):
        raise ValueError("Reused recording directory belongs to a different database run")
    validate_recording_sources(
        [{**group, "recording_source": str(directory)} for group in groups], collection=identity["collection"]
    )
    return sum(len(group["rewards"]) for group in groups)


def inherited_record(source, manifest, query_id, trial_id, score):
    name = hashlib.sha256(f"{query_id}:{trial_id}".encode()).hexdigest() + ".json.gz"
    # A source writer may move pending -> committed between our reads.
    for subdir in ("committed", "pending", "committed"):
        try:
            record = DurableRolloutOutbox._read(source / subdir / name)
            break
        except FileNotFoundError:
            continue
    else:
        raise FileNotFoundError(f"Missing inherited rollout {query_id}:{trial_id} in {source}")
    if (record["query_id"], record["trial_id"], record["status"], record["reward"]["score"]) != (
        query_id, trial_id, "completed", score
    ):
        raise ValueError(f"Inherited snapshot does not match group decision: {query_id}:{trial_id}")
    if "trace_graph" not in record:
        raise ValueError("Screening resume requires a lossless Trace DAG snapshot")
    record["metadata"] = {
        **record.get("metadata", {}),
        "inherited_from": {
            "model": manifest["model"], "run": manifest["run"], "collection": manifest["collection"],
            "query_id": query_id, "trial_id": trial_id, "recording_source": str(source),
        },
    }
    return record


async def inherit_records(outbox, groups, manifests, *, pending_limit=1024):
    """Use the normal durable writer so copied DAGs have the same replay guarantees."""
    count = 0
    for group in groups:
        source = Path(group["recording_source"])
        for trial, score in zip(group_trials(group), group["rewards"], strict=True):
            while outbox.stats()["pending_writes"] >= pending_limit:
                await asyncio.sleep(0.1)
            record = await asyncio.to_thread(
                inherited_record, source, manifests[source], str(group["source_index"]), trial, score
            )
            await outbox.enqueue(record)
            count += 1
        if count and count // 1000 != (count - len(group["rewards"])) // 1000:
            logger.info("Inherited %d confirmed rollout snapshots into the new run", count)
    return count
